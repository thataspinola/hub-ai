const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync, spawnSync } = require('node:child_process')
const { parseCommit, commits, documentation, journal, write } = require('../../tools/automation/core.cjs')

test('conventional headers, scopes, bodies and breaking changes', () => {
  for (const value of ['feat: adicionar api', 'fix(auth): renovar sessão', 'docs!: remover guia', 'refactor(api): simplificar\n\nBREAKING CHANGE: novo contrato']) assert.ok(parseCommit(value))
  for (const value of ['', 'ajustes', 'feat: ', 'unknown: texto', 'fix(): texto', 'fix: assunto\ncorpo sem separador', 'fixup! fix: texto']) assert.equal(parseCommit(value), null)
  assert.equal(parseCommit('feat(api)!: mudar').breaking, true)
  assert.equal(parseCommit('fix: ajustar\n\nBREAKING-CHANGE: contrato').breaking, true)
})

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'maintenance-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' })
  git(['init', '-q'])
  git(['config', 'user.name', 'Fixture'])
  git(['config', 'user.email', 'fixture@example.invalid'])
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'fixture', scripts: { test: 'node --test' } }))
  fs.writeFileSync(path.join(root, 'README.md'), '# Guide')
  git(['add', 'package.json', 'README.md'])
  git(['commit', '-qm', 'feat: initial'])
  return { root, git }
}

test('Git journal retains legacy messages, escapes Markdown and validates ranges', t => {
  const { root, git } = fixture(t)
  const base = git(['rev-parse', 'HEAD']).trim()
  git(['commit', '--allow-empty', '-qm', 'legacy <script>'])
  const entries = commits(root)
  assert.equal(entries.length, 2)
  assert.equal(commits(root, `${base}..HEAD`).length, 1)
  assert.match(journal(entries), /legado/)
  assert.ok(!journal(entries).includes('<script>'))
  assert.throws(() => commits(root, '--all'), /inválido/)
  assert.throws(() => commits(root, 'missing..HEAD'))
})

test('documentation is deterministic, inventories guides and detects drift', t => {
  const { root } = fixture(t)
  const result = documentation(root)
  assert.match(result, /npm run test/)
  assert.match(result, /README.md/)
  write(root, 'docs/generated/reference.md', result)
  assert.equal(documentation(root), result)
  write(root, 'docs/generated/reference.md', result, true)
  fs.writeFileSync(path.join(root, 'new-guide.md'), '# New')
  assert.throws(() => write(root, 'docs/generated/reference.md', documentation(root), true), /desatualizado/)
})

test('CLI rejects invalid commit and custom hooks without changing configuration', t => {
  const { root, git } = fixture(t)
  fs.mkdirSync(path.join(root, 'tools/automation'), { recursive: true })
  for (const file of ['core.cjs', 'cli.cjs']) fs.copyFileSync(path.join(__dirname, '../../tools/automation', file), path.join(root, 'tools/automation', file))
  const run = args => spawnSync(process.execPath, [path.join(root, 'tools/automation/cli.cjs'), ...args], { encoding: 'utf8' })
  fs.writeFileSync(path.join(root, 'message'), 'ajustes')
  assert.equal(run(['commit-file', path.join(root, 'message')]).status, 1)
  fs.writeFileSync(path.join(root, 'message'), 'fix(api): corrigir falha')
  assert.equal(run(['commit-file', path.join(root, 'message')]).status, 0)
  git(['config', 'core.hooksPath', 'corporate-hooks'])
  assert.equal(run(['hooks']).status, 1)
  assert.equal(git(['config', '--get', 'core.hooksPath']).trim(), 'corporate-hooks')
  assert.equal(run(['release-plan']).status, 1)
  assert.equal(run(['commits']).status, 0)
  const base = git(['rev-parse', 'HEAD']).trim()
  git(['commit', '--allow-empty', '-qm', 'feat(api)!: novo contrato'])
  const range = `${base}..HEAD`
  assert.equal(run(['release-plan', range]).stdout.trim(), 'major')
  assert.equal(run(['commits', range]).status, 0)
  git(['commit', '--allow-empty', '-qm', 'mensagem legada'])
  assert.equal(run(['commits', range]).status, 1)
})

test('hook installation is explicit, repeatable and preserves existing hooks', t => {
  const { root, git } = fixture(t)
  fs.mkdirSync(path.join(root, 'tools/automation'), { recursive: true })
  fs.mkdirSync(path.join(root, '.githooks'))
  for (const file of ['core.cjs', 'cli.cjs']) fs.copyFileSync(path.join(__dirname, '../../tools/automation', file), path.join(root, 'tools/automation', file))
  for (const file of ['pre-commit', 'commit-msg', 'post-commit', 'pre-push']) fs.writeFileSync(path.join(root, '.githooks', file), '#!/bin/sh\nexit 0\n')
  const run = () => spawnSync(process.execPath, [path.join(root, 'tools/automation/cli.cjs'), 'hooks'], { encoding: 'utf8' })
  const existing = path.join(root, '.git/hooks/pre-commit')
  fs.writeFileSync(existing, 'corporate hook')
  assert.equal(run().status, 1)
  assert.equal(fs.readFileSync(existing, 'utf8'), 'corporate hook')
  fs.renameSync(existing, existing + '.sample')
  assert.equal(run().status, 0)
  assert.equal(run().status, 0)
  assert.equal(git(['config', '--local', '--get', 'core.hooksPath']).trim(), '.githooks')
})
